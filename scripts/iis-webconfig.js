/* Writes build/web.config for Windows / IIS hosting (SmarterASP.NET) from vercel.json, so both hosts follow the same
 * redirects, rewrites and headers. Run after `npm run build` (see "build:iis" in package.json). Vercel ignores the file.
 * Needs the IIS "URL Rewrite" module, which SmarterASP.NET has on every plan. */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const cfg = JSON.parse(fs.readFileSync(path.join(root, 'vercel.json'), 'utf8'));
const out = path.join(root, process.env.BUILD_PATH || 'build', 'web.config');
const x = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/** "/a/:path*" -> { re: "^a(?:/(.*))?$", to(dest) } ; "/product-(.+)" keeps its own group ; plain paths match exactly */
function pattern(source, strict) {
  let p = source.replace(/^\//, '');
  let groups = 0;
  if (/:path\*$/.test(p)) { p = p.replace(/\/?:path\*$/, strict ? '/(.*)' : '(?:/(.*))?'); groups = 1; } else if (/\(.+\)/.test(p)) { groups = 1; } else { p = p.replace(/\/$/, '') + '/?'; }
  return { re: '^' + p + '$', groups };
}
const dest = (d) => d.replace(/:path\*/, '{R:1}');

let n = 0;
const rule = (name, re, action, extra = '') => `        <rule name="${x(name)} ${++n}" stopProcessing="true">\n          <match url="${x(re)}" />${extra}\n          ${action}\n        </rule>`;

const redirects = cfg.redirects.map((r) => {
  const { re } = pattern(r.source, true);   // every "/x/:path*" redirect in vercel.json has its own exact "/x" entry
  return rule('redirect', re, `<action type="Redirect" url="${x(dest(r.destination))}" redirectType="${r.permanent ? 'Permanent' : 'Found'}" />`);
});
const rewrites = cfg.rewrites.map((r) => {
  const { re } = pattern(r.source);
  return rule('rewrite', re, `<action type="Rewrite" url="${x(r.destination)}" />`);
});

// response headers
const all = {}; const noindex = []; const cache = []; let frame = null;
for (const h of cfg.headers) {
  for (const kv of h.headers) {
    if (kv.key === 'X-Robots-Tag') noindex.push(h.source);
    else if (kv.key === 'Cache-Control') cache.push([h.source, kv.value]);
    else if (kv.key === 'X-Frame-Options') frame = kv.value;
    else if (/^Content-Security-Policy/.test(kv.key)) { /* report-only policies are not carried over: they block nothing */ }
    else if (h.source === '/(.*)') all[kv.key] = kv.value;
  }
}
const srcRe = (s) => '^' + s.replace(/:path\*$/, '.*').replace(/\/$/, '/?') + (/\)$|\*$/.test(s) ? '' : '$');
const outRule = (name, header, value, cond) => `        <rule name="${x(name)} ${++n}">\n          <match serverVariable="RESPONSE_${header.replace(/-/g, '_')}" pattern=".*" />\n          <conditions><add input="{REQUEST_URI}" pattern="${x(cond.re)}"${cond.negate ? ' negate="true"' : ''} /></conditions>\n          <action type="Rewrite" value="${x(value)}" />\n        </rule>`;
const outbound = [];
if (frame) outbound.push(outRule('frame', 'X-Frame-Options', frame, { re: '^/visualizer/embed', negate: true }));
noindex.forEach((s) => outbound.push(outRule('noindex', 'X-Robots-Tag', 'noindex', { re: srcRe(s) })));
cache.forEach(([s, v]) => outbound.push(outRule('cache', 'Cache-Control', v, { re: srcRe(s) })));

const mime = { webp: 'image/webp', woff2: 'font/woff2', hdr: 'application/octet-stream', vtt: 'text/vtt', json: 'application/json', mp4: 'video/mp4', glb: 'model/gltf-binary', wasm: 'application/wasm', svg: 'image/svg+xml', webmanifest: 'application/manifest+json', txt: 'text/plain; charset=utf-8' };

const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by scripts/iis-webconfig.js from vercel.json. Do not edit by hand: change vercel.json and rebuild. -->
<configuration>
  <system.webServer>
    <defaultDocument><files><clear /><add value="index.html" /></files></defaultDocument>
    <httpErrors existingResponse="PassThrough" />
    <urlCompression doStaticCompression="true" doDynamicCompression="true" />
    <staticContent>
${Object.entries(mime).map(([e, t]) => `      <remove fileExtension=".${e}" />\n      <mimeMap fileExtension=".${e}" mimeType="${t}" />`).join('\n')}
    </staticContent>
    <httpProtocol>
      <customHeaders>
        <remove name="X-Powered-By" />
${Object.entries(all).map(([k, v]) => `        <remove name="${x(k)}" />\n        <add name="${x(k)}" value="${x(v)}" />`).join('\n')}
      </customHeaders>
    </httpProtocol>
    <rewrite>
      <rules>
        <rule name="https" stopProcessing="true">
          <match url="(.*)" />
          <conditions><add input="{HTTPS}" pattern="off" ignoreCase="true" /></conditions>
          <action type="Redirect" url="https://{HTTP_HOST}/{R:1}" redirectType="Permanent" />
        </rule>
        <rule name="no www" stopProcessing="true">
          <match url="(.*)" />
          <conditions><add input="{HTTP_HOST}" pattern="^www\\.(.+)$" /></conditions>
          <action type="Redirect" url="https://{C:1}/{R:1}" redirectType="Permanent" />
        </rule>
        <rule name="never serve leftovers of the old site or private files" stopProcessing="true">
          <match url="(\\.(pfx|dll|exe|pdb|zip|config|bak|log)$)|(^appsettings[^/]*\\.json$)|(^WebApplication2\\.)|(^wwwroot/)|(^uploads/)" ignoreCase="true" />
          <action type="CustomResponse" statusCode="404" statusReason="Not Found" statusDescription="Not Found" />
        </rule>
${redirects.join('\n')}
        <rule name="page folders" stopProcessing="true">
          <match url="^(.+?)/?$" />
          <conditions><add input="{APPL_PHYSICAL_PATH}{R:1}\\index.html" matchType="IsFile" /></conditions>
          <action type="Rewrite" url="{R:1}/index.html" />
        </rule>
${rewrites.join('\n')}
        <rule name="unknown paths show the home page" stopProcessing="true">
          <match url=".*" />
          <conditions>
            <add input="{REQUEST_FILENAME}" matchType="IsFile" negate="true" />
            <add input="{REQUEST_FILENAME}" matchType="IsDirectory" negate="true" />
            <add input="{REQUEST_URI}" pattern="\\.[a-z0-9]{2,5}($|\\?)" ignoreCase="true" negate="true" />
          </conditions>
          <action type="Rewrite" url="/index.html" />
        </rule>
      </rules>
      <outboundRules>
${outbound.join('\n')}
      </outboundRules>
    </rewrite>
  </system.webServer>
</configuration>
`;
fs.writeFileSync(out, xml);
console.log('[iis] ' + out + ': ' + redirects.length + ' redirects, ' + rewrites.length + ' rewrites, ' + outbound.length + ' header rules');
