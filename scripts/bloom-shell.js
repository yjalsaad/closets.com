/**
 * postbuild step 2 (after scripts/prerender.js): make the lean YAS Bloom shell point at the real, hashed bundle names.
 *
 * public/yas-bloom/shell.html (copied to <build>/yas-bloom/shell.html by CRA) already works on its own: its fallback block reads /asset-manifest.json at run time.
 * This step replaces that block with the same tags CRA writes into index.html (stylesheet + deferred main script), so the browser discovers the bundle straight from
 * the HTML (no extra manifest round trip), and adds <link rel=preload> for the showroom's lazy chunks, which main.js would otherwise request only after it has run.
 *
 * FAIL SOFT, like prerender.js: any problem (file missing, entry not found, a referenced file not on disk) leaves the shell untouched (the fallback keeps working)
 * and exits 0. It only ever writes <build>/yas-bloom/shell.html; nothing else in the build is read-write.
 */
const fs = require('fs');
const path = require('path');

const BUILD_DIR = path.resolve(process.cwd(), process.env.BUILD_PATH || 'build');
const SHELL = path.join(BUILD_DIR, 'yas-bloom', 'shell.html');
const BLOCK = /<!--BLOOM-ENTRY:BEGIN[\s\S]*?<!--BLOOM-ENTRY:END-->/;

function build(manifest, mainSrc) {
  const files = manifest.files || {}, entry = manifest.entrypoints || [];
  const css = entry.filter((f) => /\.css$/.test(f)), js = entry.filter((f) => /\.js$/.test(f));
  if (!js.length) throw new Error('no JS entrypoint in asset-manifest.json');
  const url = (f) => '/' + String(f).replace(/^\//, '');
  const must = (u) => { if (!fs.existsSync(path.join(BUILD_DIR, u))) throw new Error('missing ' + u); return u; };
  const tags = [];
  // the showroom lazy chunk (webpackChunkName "showroom3d") and the chunks main.js loads together with it: Promise.all([n.e(113),n.e(248)])
  const pre = [];
  try {
    const sJs = files['showroom3d.js'], sCss = files['showroom3d.css'];
    if (sJs) {
      const id = (/(\d+)===\w\?"showroom3d"/.exec(mainSrc) || [])[1];
      const calls = mainSrc.match(/Promise\.all\(\[(?:\w\.e\(\d+\),?)+\]\)\.then\(\w\.bind\(\w,\d+\)\)/g) || [];
      const call = id && calls.find((c) => c.includes('.e(' + id + ')'));
      const deps = call ? [...call.matchAll(/\.e\((\d+)\)/g)].map((m) => m[1]).filter((x) => x !== id) : [];
      for (const d of deps) {
        const key = Object.keys(files).find((k) => new RegExp('^static/js/' + d + '\\.[0-9a-f]+\\.chunk\\.js$').test(k));
        if (key) pre.push('<link rel="preload" as="script" href="' + must(url(files[key])) + '">');
      }
      pre.push('<link rel="preload" as="script" href="' + must(url(sJs)) + '">');
      if (sCss) pre.push('<link rel="preload" as="style" href="' + must(url(sCss)) + '">');
    }
  } catch (e) { pre.length = 0; console.warn('[bloom-shell] chunk preloads skipped: ' + e.message); }
  for (const f of css) tags.push('<link rel="stylesheet" href="' + must(url(f)) + '">');
  tags.push(...pre);
  for (const f of js) tags.push('<script defer src="' + must(url(f)) + '" onerror="window.__bloomFail&&window.__bloomFail()"></script>');
  return tags.join('\n');
}

try {
  if (!fs.existsSync(SHELL)) { console.warn('[bloom-shell] ' + SHELL + ' not found, skipping.'); process.exit(0); }
  const html = fs.readFileSync(SHELL, 'utf8');
  if (!BLOCK.test(html)) { console.warn('[bloom-shell] marker block not found, skipping.'); process.exit(0); }
  const manifest = JSON.parse(fs.readFileSync(path.join(BUILD_DIR, 'asset-manifest.json'), 'utf8'));
  const mainFile = (manifest.entrypoints || []).find((f) => /\.js$/.test(f));
  const mainSrc = mainFile ? fs.readFileSync(path.join(BUILD_DIR, mainFile), 'utf8') : '';
  const out = html.replace(BLOCK, () => '<!--BLOOM-ENTRY: generated by scripts/bloom-shell.js-->\n' + build(manifest, mainSrc) + '\n');
  fs.writeFileSync(SHELL, out);
  console.log('[bloom-shell] ' + path.relative(process.cwd(), SHELL) + ' now references ' + (manifest.entrypoints || []).join(', '));
} catch (e) {
  console.warn('[bloom-shell] skipped (shell keeps its run-time fallback): ' + e.message);
}
process.exit(0);
